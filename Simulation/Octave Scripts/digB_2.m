%% ECE 351s - Digital Communication, Part B, Item 2: Digital Modulation (BPSK)
%  Transmitter + coherent receiver, LO phase error (30/60/90 deg), bit errors,
%  and the effect of the line code (AMI) on the transmitted spectrum.
%  Works in Octave and MATLAB. No toolbox communication functions are used:
%  every block (polar NRZ / AMI generator, modulator, mixer, ideal LPF,
%  bit decision, PSD estimator) is built here from basic theory.
%  Run the whole file; figures are also saved as PNGs in a "digB_2_figures"
%  folder next to this script (relative path, no editing).
%
%  Normalisation (same as Item 1): Tb = 1 s, so Rb = 1 bit/s and every
%  frequency below is also "in units of Rb".  fc = 10 Hz > Rb, as required.

clear; close all; clc;
saveFigs = true;
set(0,'DefaultFigurePosition',[100 100 1150 780]);      % bigger figures so nothing is cramped
set(0,'DefaultFigurePaperPositionMode','auto');
% legends go OUTSIDE the axes (right side) so they never cover the curves
leg = @(varargin) legend(varargin{:},'Location','eastoutside');
if exist('OCTAVE_VERSION','builtin'), rand('state',351); randn('state',351); else, rng(351); end

%% ---------------------------------------------------------------------
%  0. SETUP
%  ---------------------------------------------------------------------
Tb   = 1;                    % bit duration [s]            (as in Item 1)
Rb   = 1/Tb;                 % bit rate [bit/s]
fc   = 10;                   % carrier [Hz]  (10 x Rb > Rb, 10 full cycles per bit)
A    = 1;                    % carrier amplitude [V]
Nb   = 64;                   % bits in the demonstration stream (>= 64 required)
fsim = 1000;                 % simulation grid [Hz]: 100 samples per carrier cycle,
dt   = 1/fsim;               %   keeps spectral aliasing of the sinc tails negligible
spb  = round(fsim*Tb);       % samples per bit
L    = Nb*spb;               % samples in the demonstration stream
t    = (0:L-1)/fsim;         % time axis [s]
phis = [0 30 60 90];         % LO phase errors to study [deg]
fcutRx = 4*Rb;               % receiver low-pass cut-off [Hz] (removes the 2fc = 20 Hz term)

% small helpers (anonymous functions so the file is MATLAB/Octave portable)
mysinc  = @(x) (x==0) + (x~=0).*sin(pi*x)./(pi*x + (x==0));      % sin(pi x)/(pi x)
fAxis   = @(n) (-n/2:n/2-1)*(fsim/n);                              % centred frequency axis [Hz]
applyH  = @(x,H) real(ifft(ifftshift(fftshift(fft(x)).*H)));      % filter in frequency domain
polarNRZ = @(bits) kron(2*bits-1, ones(1,spb));                    % bit 1 -> +1, bit 0 -> -1
amiRZ    = @(bits) kron(bits.*((-1).^(cumsum(bits)-1)), ...        % bit 1 -> alternating +-1,
                        [ones(1,spb/2) zeros(1,spb/2)]);           % half-width pulse; bit 0 -> 0
PdB     = @(P,ref) 10*log10(P/ref + 1e-12);                        % PSD in dB relative to ref
cosd_   = @(x) cos(x*pi/180);                                      % cosine of an angle in degrees
savefig_ = @(name) print('-dpng','-r110',fullfile('digB_2_figures',[name '.png']));
if saveFigs && ~exist('digB_2_figures','dir'), mkdir('digB_2_figures'); end

% theory: PSD of polar NRZ and of AMI(half-width) baseband, and of the BPSK signals
Sb_polar = @(f) A^2*Tb*mysinc(f*Tb).^2;
Sb_ami   = @(f) A^2*(Tb/4)*mysinc(f*Tb/2).^2 .* sin(pi*f*Tb).^2;
S_bpsk   = @(f) 0.25*(Sb_polar(f-fc) + Sb_polar(f+fc));            % s(t) = b(t)cos(2 pi fc t)
S_amipsk = @(f) 0.25*(Sb_ami(f-fc)   + Sb_ami(f+fc));

% bandwidth by the project's 1 % rule: largest frequency where |S(f)| >= 1 % of its max
bw1pct = @(f,P) 2*(max(f(f>0 & sqrt(P) >= 0.01*max(sqrt(P(f>0))))) - fc);

% ---- random bit stream (generated by the program) ----
bits = round(rand(1,Nb));
b    = polarNRZ(bits);                       % baseband polar NRZ waveform b(t)
f    = fAxis(L);                             % df = 1/(Nb*Tb) = 1/64 Hz

fprintf('Bit stream (%d bits): %s\n', Nb, num2str(bits,'%d'));
fprintf('Rb = %g bit/s, fc = %g Hz (fc > Rb: %d)\n', Rb, fc, fc > Rb);

%% ---------------------------------------------------------------------
%  ITEM 2(a): BPSK TRANSMITTER AND COHERENT RECEIVER
%  ---------------------------------------------------------------------
%  Tx :  s(t) = A b(t) cos(2 pi fc t)           (phase 0 for bit 1, pi for bit 0)
%  Rx :  v(t) = s(t) * 2cos(2 pi fc t + phi)    (mixer / coherent detector)
%        v(t) = A b(t)[cos(phi) + cos(4 pi fc t + phi)]
%        y(t) = LPF{v(t)} = A b(t) cos(phi)     (the 2fc term is removed)
%        decision: sample y at the middle of every bit, bit = 1 if y > 0
Hlp = double(abs(f) <= fcutRx);                       % ideal LPF (brick wall in frequency)
c0  = cos(2*pi*fc*t);
s   = A*b.*c0;                                        % transmitted signal
mid = (0:Nb-1)*spb + spb/2 + 1;                       % index of the middle of each bit

y = zeros(numel(phis), L);  yS = zeros(numel(phis), Nb);
rxBits = zeros(numel(phis), Nb);  nErr = zeros(1,numel(phis));  ampMeas = zeros(1,numel(phis));
for i = 1:numel(phis)
    phi = phis(i)*pi/180;
    v = s .* (2*cos(2*pi*fc*t + phi));                % coherent detector: mixer
    y(i,:) = applyH(v, Hlp);                          % ... followed by the LPF
    yS(i,:) = y(i,mid);                               % sample at mid-bit
    rxBits(i,:) = double(yS(i,:) > 0);                % decision threshold = 0
    nErr(i) = sum(rxBits(i,:) ~= bits);
    ampMeas(i) = mean(abs(yS(i,:)));
end
eyeOpen = min(b(mid).*yS(1,:));                       % worst-case mid-bit margin, phi = 0
fprintf('phi = 0: received stream identical to transmitted: %d (bit errors = %d)\n', ...
        isequal(rxBits(1,:),bits), nErr(1));

%% ---------------------------------------------------------------------
%  POWER SPECTRAL DENSITY by averaging (Welch): 256 random blocks of 64 bits
%  ---------------------------------------------------------------------
%  Each block is multiplied by a Hann window (built by hand), its periodogram
%  is computed with the FFT and all periodograms are averaged.  The same
%  random blocks feed: BPSK(polar NRZ) at Tx, the receiver output, the
%  baseband b(t), and BPSK modulated by the AMI waveform (item 2e).
%  Every block gets a RANDOM carrier phase.  With fc = 10 Rb the carrier would
%  otherwise be locked to the bit clock, and the two spectral images of the
%  signal would add coherently in the tails (about 1.3 x the textbook PSD).
%  A random phase models a link whose carrier has no fixed relation to the
%  bit timing, which is what the standard sinc^2 formula assumes.
nBlk = 256;
w  = 0.5*(1 - cos(2*pi*(0:L-1)/L));                   % Hann window
U  = sum(w.^2);
psd = @(x) fftshift((dt/U)*abs(fft(w.*x)).^2);        % V^2/Hz, centred
P_tx = zeros(1,L); P_ami = zeros(1,L); P_b = zeros(1,L); P_y = zeros(1,L);
for k = 1:nBlk
    bk  = round(rand(1,Nb));
    bb  = polarNRZ(bk);   aa = amiRZ(bk);
    ck  = cos(2*pi*fc*t + 2*pi*rand);                 % carrier with random phase
    s1  = A*bb.*ck;       s2 = A*aa.*ck;
    y1  = applyH(s1.*(2*ck), Hlp);                    % receiver output (LO phase = carrier phase)
    P_tx  = P_tx  + psd(s1);   P_ami = P_ami + psd(s2);
    P_b   = P_b   + psd(bb);   P_y   = P_y   + psd(y1);
end
P_tx = P_tx/nBlk;  P_ami = P_ami/nBlk;  P_b = P_b/nBlk;  P_y = P_y/nBlk;

% ---- bandwidth of the BPSK signal ----
selU = f > fc+0.5 & f < fc+1.5;                       % first null above the carrier
[~,iN] = min(P_tx(selU));  fU = f(selU);  fNull = fU(iN);
BW_null  = 2*(fNull - fc);                            % null-to-null (theory 2/Tb = 2 Rb)
BW_1pct  = bw1pct(f,P_tx);                            % project criterion, simulated
BW_1pctT = bw1pct(f,S_bpsk(f));                       % project criterion, from the theory curve
fprintf('BPSK: first null at fc + %.3f Hz -> null-to-null BW = %.3f Hz (theory %g Hz)\n', fNull-fc, BW_null, 2*Rb);
fprintf('BPSK: 1%% bandwidth = %.2f Hz (theory curve: %.2f Hz)\n', BW_1pct, BW_1pctT);

%% ---------------------------------------------------------------------
%  ITEM 2(b): WAVEFORMS AND SPECTRA AT THE Tx OUTPUT AND AT THE Rx OUTPUT
%  ---------------------------------------------------------------------
tw = t <= 8;                                          % first 8 bits, so the carrier is visible

figure('Name','Item 2b: transmitter output');
subplot(2,1,1);
plot(t(tw), s(tw), 'b', 'LineWidth', 1.0); hold on;
plot(t(tw), b(tw), 'r--', 'LineWidth', 1.5);
for k = 1:8, text(k-0.5, 1.35, sprintf('%d',bits(k)), 'HorizontalAlignment','center','FontWeight','bold'); end
grid on; ylim([-1.6 1.6]); xlabel('Time (s)'); ylabel('Amplitude (V)');
leg('BPSK signal s(t)','data b(t) (polar NRZ)');
title({'Item 2(b): BPSK transmitter output, first 8 bits (bit values on top)', ...
       'phase reversal of the carrier at every 1 \leftrightarrow 0 transition'});
subplot(2,1,2);
plot(f, PdB(P_tx, max(P_tx)), 'b', 'LineWidth', 1.3); hold on;
plot(f, PdB(S_bpsk(f), max(P_tx)), 'r--', 'LineWidth', 1.3);
yl = [-70 5];
plot([fc-Rb fc-Rb NaN fc+Rb fc+Rb],[yl(1) yl(2) NaN yl(1) yl(2)],'k:','LineWidth',1.2);
grid on; xlim([-20 20]); ylim(yl); xlabel('Frequency (Hz)'); ylabel('PSD (dB rel. peak)');
leg('simulated (256 blocks)','theory (A^2T_b/4)[sinc^2 terms]','first nulls f_c \pm R_b');
title({'Item 2(b): PSD of the BPSK signal at the transmitter output', ...
       sprintf('null-to-null bandwidth = %.2f Hz = 2R_b;  1%% bandwidth = %.1f Hz',BW_null,BW_1pct)});
if saveFigs, savefig_('01_item2b_tx'); end

figure('Name','Item 2b: receiver output');
subplot(3,1,1);
plot(t(tw), b(tw), 'r--', 'LineWidth', 1.5); hold on;
plot(t(tw), y(1,tw), 'b', 'LineWidth', 1.3);
idx = mid(1:8);  plot(t(idx), y(1,idx), 'ko', 'MarkerFaceColor','g', 'MarkerSize', 6);
grid on; ylim([-1.5 1.5]); xlabel('Time (s)'); ylabel('Amplitude (V)');
leg('transmitted data b(t)','detector output y(t)','mid-bit sampling instants');
title('Item 2(b): coherent receiver output (\phi = 0^\circ), first 8 bits');
subplot(3,1,2);
stairs(0:Nb, [bits bits(end)], 'r', 'LineWidth', 1.5); hold on;
plot((1:Nb)-0.5, rxBits(1,:), 'bo', 'MarkerSize', 5);
grid on; xlim([0 Nb]); ylim([-0.2 1.2]); xlabel('Time (s)  (one bit per second)'); ylabel('Logic level');
leg('transmitted bits','received bits');
title(sprintf('Item 2(d): received vs transmitted stream, \\phi = 0^\\circ: %d bit errors out of %d', nErr(1), Nb));
subplot(3,1,3);
plot(f, PdB(P_b, max(P_b)), 'r', 'LineWidth', 1.5); hold on;
plot(f, PdB(P_y, max(P_b)), 'b--', 'LineWidth', 1.3);
grid on; xlim([-6 6]); ylim([-60 5]); xlabel('Frequency (Hz)'); ylabel('PSD (dB rel. peak)');
leg('transmitted data b(t)','receiver output y(t)');
title(sprintf('Item 2(b): PSD at the receiver output = baseband data, cut by the LPF at %gR_b = %g Hz', fcutRx/Rb, fcutRx));
if saveFigs, savefig_('02_item2b_rx'); end

%% ---------------------------------------------------------------------
%  ITEM 2(c) and 2(d): LOCAL OSCILLATOR PHASE ERROR 30, 60, 90 degrees
%  ---------------------------------------------------------------------
%  y(t) = A b(t) cos(phi): amplitude shrinks by cos(phi); at 90 deg it is zero
%  (quadrature null) and the decision is made on leakage only.
figure('Name','Item 2c: phase error');
subplot(2,1,1);
plot(t(tw), b(tw), 'k', 'LineWidth', 1.6); hold on;
col = {'b','g','m','r'};
for i = 1:numel(phis)
    plot(t(tw), y(i,tw), col{i}, 'LineWidth', 1.3);
end
grid on; ylim([-1.3 1.3]); xlabel('Time (s)'); ylabel('Amplitude (V)');
leg('data b(t)','\phi = 0^\circ','\phi = 30^\circ','\phi = 60^\circ','\phi = 90^\circ (quadrature null)');
title('Item 2(c): detector output y(t) for different LO phase errors, first 8 bits');
subplot(2,1,2);
pp = 0:1:180;
plot(pp, cosd_(pp), 'k', 'LineWidth', 1.4); hold on;
plot(phis, ampMeas/ampMeas(1), 'ro', 'MarkerFaceColor','r', 'MarkerSize', 7);
grid on; xlim([0 180]); ylim([-1.1 1.1]); xlabel('LO phase error \phi (degrees)'); ylabel('Amplitude relative to \phi = 0 (V/V)');
leg('theory cos\phi','simulated mean |y| at mid-bit, relative to \phi = 0');
title('Item 2(c): recovered amplitude follows cos\phi (for \phi > 90^\circ cos\phi < 0 would invert every bit)');
if saveFigs, savefig_('03_item2c_phase'); end

%% ---------------------------------------------------------------------
%  ITEM 2(e): LINE-CODED WAVEFORM (AMI) APPLIED TO THE MODULATOR
%  ---------------------------------------------------------------------
%  Same carrier, but the modulating waveform is the AMI waveform of Item 1
%  (marks alternate +1/-1 in half-width pulses, spaces are 0) instead of
%  the polar NRZ waveform.  The modulator is a product, so the PSD is the
%  baseband PSD shifted to +-fc:  S(f) = (1/4)[Sb(f-fc) + Sb(f+fc)].
ami  = amiRZ(bits);
sAmi = A*ami.*c0;
% receiver check: mix with 2cos(2 pi fc t), integrate over the first half of
% every bit (where the AMI pulse lives); a mark gives +-0.5, a space gives 0
vA   = sAmi .* (2*c0);
vAm  = reshape(vA, spb, Nb);                          % one column per bit
zA   = sum(vAm(1:spb/2,:), 1)*dt;
amiDec = double(abs(zA) > 0.25);
nErrAmi = sum(amiDec ~= bits);
BW_1pctAmi  = bw1pct(f,P_ami);
BW_1pctAmiT = bw1pct(f,S_amipsk(f));
[~,iC] = min(abs(f - fc));
notchDepth = PdB(P_ami(iC), max(P_ami));              % dB below its own peak at f = fc
fprintf('AMI-PSK: receiver decodes the AMI stream with %d bit errors\n', nErrAmi);
fprintf('AMI-PSK: 1%% bandwidth = %.2f Hz (theory curve %.2f Hz); notch at fc = %.1f dB\n', ...
        BW_1pctAmi, BW_1pctAmiT, notchDepth);
fprintf('Average power: polar-NRZ BPSK = %.3f V^2, AMI-PSK = %.3f V^2\n', ...
        sum(P_tx)*(fsim/L), sum(P_ami)*(fsim/L));

figure('Name','Item 2e: line-coded modulation');
subplot(2,1,1);
plot(t(tw), sAmi(tw), 'b', 'LineWidth', 1.0); hold on;
plot(t(tw), ami(tw), 'r--', 'LineWidth', 1.5);
for k = 1:8, text(k-0.5, 1.35, sprintf('%d',bits(k)), 'HorizontalAlignment','center','FontWeight','bold'); end
grid on; ylim([-1.6 1.6]); xlabel('Time (s)'); ylabel('Amplitude (V)');
leg('AMI-modulated s(t)','AMI waveform');
title({'Item 2(e): carrier modulated by the AMI waveform, first 8 bits', ...
       'three amplitude levels, no constant envelope'});
subplot(2,1,2);
ref = max(P_tx);
plot(f, PdB(P_tx,  ref), 'b', 'LineWidth', 1.4); hold on;
plot(f, PdB(P_ami, ref), 'r', 'LineWidth', 1.4);
plot(f, PdB(S_bpsk(f),   ref), 'b--', 'LineWidth', 1.0);
plot(f, PdB(S_amipsk(f), ref), 'r--', 'LineWidth', 1.0);
grid on; xlim([fc-6 fc+6]); ylim([-70 5]); xlabel('Frequency (Hz)'); ylabel('PSD (dB rel. polar-NRZ peak)');
leg('polar NRZ (simulated)','AMI (simulated)','polar NRZ (theory)','AMI (theory)');
title({'Item 2(e): transmitted PSD around the carrier (positive side)', ...
       'AMI: notch at f_c (no power at DC before modulation), lobes at f_c \pm 0.5R_b'});
if saveFigs, savefig_('04_item2e_linecode'); end

%% ---------------------------------------------------------------------
%  EXTRA (not required): bit error rate versus LO phase error with noise
%  ---------------------------------------------------------------------
%  Without noise a phase error of 30 or 60 deg only shrinks the amplitude, so
%  no errors appear.  With AWGN the smaller amplitude costs noise margin:
%  Pe = Q( sqrt(2Eb/N0) cos(phi) ) = 0.5 erfc( sqrt(Eb/N0) cos(phi) ).
%  Same transmitted stream and same noise for every phi; integrate-and-dump detector.
fsM = 100; spbM = fsM*Tb; dtM = 1/fsM; NbM = 20000; EbN0dB = 6;
Eb = A^2*Tb/2;  N0 = Eb/10^(EbN0dB/10);  sig2 = N0/(2*dtM);     % noise power per sample
bM = round(rand(1,NbM));  tM = (0:NbM*spbM-1)/fsM;
r  = A*kron(2*bM-1, ones(1,spbM)).*cos(2*pi*fc*tM) + sqrt(sig2)*randn(1,NbM*spbM);
phiSweep = 0:10:180;  berM = zeros(size(phiSweep));
for i = 1:numel(phiSweep)
    z = sum(reshape(r.*(2*cos(2*pi*fc*tM + phiSweep(i)*pi/180)), spbM, NbM), 1)*dtM/Tb;
    berM(i) = mean(double(z > 0) ~= bM);
end
berT = 0.5*erfc(sqrt(Eb/N0)*cosd_(phiSweep));
figure('Name','Extra: BER vs phase error');
semilogy(phiSweep, max(berT,1e-5), 'k', 'LineWidth', 1.4); hold on;
semilogy(phiSweep, max(berM,1e-5), 'ro', 'MarkerFaceColor','r', 'MarkerSize', 6);
grid on; xlim([0 180]); xlabel('LO phase error \phi (degrees)'); ylabel('Bit error rate');
leg('theory 0.5 erfc(\surd(E_b/N_0) cos\phi)','simulation (20000 bits)');
title(sprintf('Extra: BPSK bit error rate vs LO phase error, E_b/N_0 = %d dB',EbN0dB));
if saveFigs, savefig_('05_extra_ber_vs_phase'); end
[~,i30] = min(abs(phiSweep-30)); [~,i60] = min(abs(phiSweep-60)); [~,i90] = min(abs(phiSweep-90));

%% ---------------------------------------------------------------------
%  NUMBERS FOR THE SUMMARY TABLE
%  ---------------------------------------------------------------------
fprintf('\n================ RESULTS (Digital Part B, item 2) ================\n');
fprintf('Modulation: BPSK, Rb = %g bit/s, fc = %g Hz, fsim = %g Hz, %d bits\n',Rb,fc,fsim,Nb);
fprintf('[2a] receiver LPF cut-off = %g Hz ; worst-case mid-bit margin (phi=0) = %.3f V\n',fcutRx,eyeOpen);
fprintf('[2b] BPSK null-to-null BW = %.3f Hz (theory 2Rb = %g Hz) ; 1%% BW = %.2f Hz (theory curve %.2f Hz)\n', ...
        BW_null, 2*Rb, BW_1pct, BW_1pctT);
for i = 1:numel(phis)
    fprintf('[2c/2d] phi = %2d deg: mean |y| = %.4f V = %.4f x (phi=0 value) (cos(phi) = %.4f) ; bit errors = %d / %d\n', ...
            phis(i), ampMeas(i), ampMeas(i)/ampMeas(1), cosd_(phis(i)), nErr(i), Nb);
end
fprintf('[2c/2d] phi = 90 deg: max |y| at the sampling instants = %.2e V ; ones in the stream = %d ; decisions "1" = %d\n', ...
        max(abs(yS(end,:))), sum(bits), sum(rxBits(end,:)));
fprintf('[2e] AMI-PSK: 1%% BW = %.2f Hz (theory curve %.2f Hz) ; notch at fc = %.1f dB ; decode errors = %d\n', ...
        BW_1pctAmi, BW_1pctAmiT, notchDepth, nErrAmi);
fprintf('[extra] BER at Eb/N0 = %d dB, 20000 bits: phi=0: %.2e (theory %.2e) ; 30: %.2e (%.2e) ; 60: %.2e (%.2e) ; 90: %.3f (%.3f)\n', ...
        EbN0dB, berM(1),berT(1), berM(i30),berT(i30), berM(i60),berT(i60), berM(i90),berT(i90));
fprintf('==================================================================\n');
